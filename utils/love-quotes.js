const storage = require('./storage');

function getTodayQuote() {
  const today = new Date();
  const todayStr = `${today.getFullYear()}-${today.getMonth() + 1}-${today.getDate()}`;
  const lastDate = storage.getLastQuoteDate();

  if (lastDate === todayStr) {
    const lastIdx = storage.getLastQuoteIndex();
    if (lastIdx >= 0 && lastIdx < quotes.length) {
      return quotes[lastIdx];
    }
  }

  // 新的一天，随机选一句（但与昨天不同）
  const lastIdx = storage.getLastQuoteIndex();
  let idx;
  do {
    idx = Math.floor(Math.random() * quotes.length);
  } while (idx === lastIdx && quotes.length > 1);

  storage.setLastQuoteDate(todayStr);
  storage.setLastQuoteIndex(idx);
  return quotes[idx];
}

module.exports = { quotes, getTodayQuote };
